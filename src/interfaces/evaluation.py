from abc import ABC, abstractmethod

class BaseEvaluator(ABC):
    @abstractmethod
    def evaluate(self, query: str, retrieved_context: str, generated_response: str, ground_truth: str = None) -> dict:
        """
        Evaluate RAG generation against retrieval context and/or ground truth.

        Args:
            query: Customer query.
            retrieved_context: Combined content of retrieved policy context.
            generated_response: Response generated by the RAG pipeline.
            ground_truth: Optional ideal target response.

        Returns:
            dict: {
                'faithfulness': float,      # Is the answer backed by retrieved text? (0-5 scale or 0-1)
                'answer_relevance': float,  # Does it address the question? (0-5 scale or 0-1)
                'context_recall': float,    # Did we retrieve the necessary information? (0-5 scale or 0-1)
                'reasoning': dict           # Explanations behind the scores
            }
        """
        pass
